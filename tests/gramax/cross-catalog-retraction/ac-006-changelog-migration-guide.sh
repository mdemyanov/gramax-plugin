#!/usr/bin/env bash
# tests/gramax/cross-catalog-retraction/ac-006-changelog-migration-guide.sh
# Требование: content/30-requirements/2026-08-13-cross-catalog-retraction.md, AC-006
#             (FR-100/FR-101).
# ADR: content/00-project/adr/0017-cross-catalog-retraction.md, Решение 3 — точный текст
#      секции «## 4.2.1».
#
# НАХОДКА QA-author (расхождение BA/SA-текста, зафиксировано в at-design.md «Находки», не
# «исправлено» тихо): буквальный текст AC-006 требования говорит «всех четырёх смысловых
# элементов (а)-(г)», хотя FR-100 перечисляет ПЯТЬ пунктов (а)-(д), и сам ADR-0017 («Edge
# cases», раздел «Контракт с QA-author») прямо пишет «независимый сигнал нужен на каждый из
# пяти под-пунктов FR-100 (а–д)». Этот скрипт проверяет все ПЯТЬ — строгое надмножество
# буквальных «четырёх» требования: 100%-покрытие буквы AC-006 гарантированно достигается при
# покрытии всех пяти.
#
# Природа: живой контракт — КРАСНЫЙ на момент создания. Секции «## 4.2.1» в CHANGELOG.md нет
# вовсе (FR-102, версионирование — фаза Tech-writer, ещё не наступила).
#
# Ограничение негативной проверки (честно, не имитация полноты): «отсутствие явного упоминания
# стороннего репозитория-потребителя» (FR-101) в общем виде НЕ grep-детектируемо — нельзя
# перечислить регуляркой все возможные будущие имена репозиториев. Автоматизированы только
# ДВА КОНКРЕТНЫХ, уже известных случая утечки (content/lessons-learned.md, 2026-08-11:
# `knowlage/moex`, `mango-cti-rest`) плюс прокси-проверка на повторное введение отклонённой
# ADR-0017 «рабочей» формы `../../`. Полная гарантия — ручной обзор Tech-writer/QA-runner перед
# публикацией CHANGELOG-записи (см. README.md → «Ручная проверка»).

set -u -o pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel)"
source "$SCRIPT_DIR/lib/assert.sh"

FAIL=0
CHANGELOG="$ROOT/plugins/gramax/CHANGELOG.md"

assert_file_exists "$CHANGELOG" "AC-006: CHANGELOG.md должен существовать"

if [ -f "$CHANGELOG" ]; then
  # Изолируем секцию "## 4.2.1" от следующего "## "-заголовка (или EOF) — позитивное
  # предусловие: секция вообще существует. Без этого шага пустая секция дала бы вакуумный PASS
  # на всех последующих grep (пустой ввод, лишённый содержательного сигнала — тот же класс
  # дефекта, что content/lessons-learned.md, 2026-08-11, «grep|xargs|xargs молча PASS'ит»).
  # Порядок действий внутри awk важен: проверка «следующий заголовок» должна идти ДО print —
  # иначе строка самого следующего заголовка попадёт в вывод (проверено на синтетической
  # фикстуре при написании этого suite'а).
  SECTION="$(awk '/^## 4\.2\.1( |$)/{flag=1} /^## / && flag && !/^## 4\.2\.1( |$)/{exit} flag{print}' "$CHANGELOG")"

  if [ -z "$SECTION" ]; then
    echo "  FAIL: AC-006 — секция '## 4.2.1' отсутствует в CHANGELOG.md вовсе (FR-100/FR-102)" >&2
    FAIL=$((FAIL + 1))
  else
    # НАХОДКА (эмпирическая, на синтетической фикстуре при написании этого скрипта): CHANGELOG.md
    # этого репозитория пишется с ручным переносом строк на ~90 столбце (тот же стиль, что
    # content/*.md и ADR-тексты) — точный текст Решения 3 ADR-0017 переносит фразу «не\nизменилась»
    # ровно на границе строк. Построчный grep на 'не измени' даёт ЛОЖНЫЙ FAIL на буквально
    # корректном, дословно скопированном из ADR тексте — то есть «красный TDD-stub, который
    # нельзя погасить корректной работой» (content/lessons-learned.md, 2026-08-11). Все проверки
    # ниже идут по SECTION_FLAT (переводы строк схлопнуты в пробел), не по $SECTION напрямую.
    SECTION_FLAT="$(printf '%s' "$SECTION" | tr '\n' ' ')"

    # (а) рецепт не работает — установлено probe
    if ! printf '%s' "$SECTION_FLAT" | grep -qiE 'не работает'; then
      echo "  FAIL: AC-006(а) — секция не констатирует, что рецепт 'не работает' (FR-100а)" >&2
      FAIL=$((FAIL + 1))
    fi
    # (б) исправление документационное
    if ! printf '%s' "$SECTION_FLAT" | grep -qiE 'документационн'; then
      echo "  FAIL: AC-006(б) — секция не указывает, что исправление документационное (FR-100б)" >&2
      FAIL=$((FAIL + 1))
    fi
    # (в) рекомендация inline code не изменилась — два независимых анкера одного элемента
    if ! printf '%s' "$SECTION_FLAT" | grep -qiE 'inline code'; then
      echo "  FAIL: AC-006(в) — секция не подтверждает рекомендацию 'inline code' (FR-100в)" >&2
      FAIL=$((FAIL + 1))
    fi
    if ! printf '%s' "$SECTION_FLAT" | grep -qiE 'не измени'; then
      echo "  FAIL: AC-006(в) — секция не подтверждает, что рекомендация 'не изменилась' (FR-100в)" >&2
      FAIL=$((FAIL + 1))
    fi
    # (г) самопроверка потребителя
    if ! printf '%s' "$SECTION_FLAT" | grep -qiE 'не оправдается|ожидание не оправд'; then
      echo "  FAIL: AC-006(г) — секция не содержит самопроверку потребителя ('ожидание не оправдается') (FR-100г)" >&2
      FAIL=$((FAIL + 1))
    fi
    # (д) локальный скилл-дубль — пересинхронизация
    if ! printf '%s' "$SECTION_FLAT" | grep -qiE 'скилл-дубл'; then
      echo "  FAIL: AC-006(д) — секция не упоминает локальный скилл-дубль (FR-100д)" >&2
      FAIL=$((FAIL + 1))
    fi
    if ! printf '%s' "$SECTION_FLAT" | grep -qiE 'пересинхрон'; then
      echo "  FAIL: AC-006(д) — секция не даёт инструкцию пересинхронизации (FR-100д)" >&2
      FAIL=$((FAIL + 1))
    fi

    # Негативные проверки (FR-101) — 0 вхождений, ограниченный, но честный охват (см. заголовок).
    if printf '%s' "$SECTION_FLAT" | grep -qF '../../'; then
      echo "  FAIL: AC-006 (негатив) — секция вводит паттерн '../../' (непубликуемая рабочая форма, явно отклонена ADR-0017 Решение 2) — нарушение FR-101" >&2
      FAIL=$((FAIL + 1))
    fi
    if printf '%s' "$SECTION_FLAT" | grep -qiE 'knowlage/moex|mango-cti-rest'; then
      echo "  FAIL: AC-006 (негатив) — секция называет известный приватный сторонний репозиторий-потребитель (content/lessons-learned.md, 2026-08-11) — нарушение FR-101" >&2
      FAIL=$((FAIL + 1))
    fi
  fi
fi

if [ "$FAIL" -gt 0 ]; then fail_msg "ac-006: $FAIL assertion(s) failed"; exit 1; fi
pass_msg "ac-006: секция CHANGELOG 4.2.1 несёт все пять элементов FR-100 и не выходит за периметр FR-101 (в пределах честного охвата негативной проверки)"
