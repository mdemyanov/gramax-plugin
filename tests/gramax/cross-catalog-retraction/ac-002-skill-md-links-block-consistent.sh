#!/usr/bin/env bash
# tests/gramax/cross-catalog-retraction/ac-002-skill-md-links-block-consistent.sh
# Требование: content/30-requirements/2026-08-13-cross-catalog-retraction.md, AC-002
#             (FR-095/FR-096).
# ADR: content/00-project/adr/0017-cross-catalog-retraction.md, Решение 2 — точный текст замены
#      блока «## Ссылки» SKILL.md (закрывает FR-095 и FR-096 одним изменением).
#
# Природа: смешанная, три независимых сигнала разной природы.
#   (a) негативная — КРАСНАЯ сегодня: SKILL.md:220 всё ещё содержит «Полный рецепт (реальный
#       `code:`)».
#   (b) позитивная — уже ЗЕЛЁНАЯ сегодня (regression guard, BR-002 требования): «inline code»
#       рекомендован SKILL.md:215 с первого коммита плагина — эта половина AC защищает
#       рекомендацию от случайной потери вместе с ретируемым рецептом, не ждёт Dev.
#   (в) семантическая — ЧАСТИЧНО автоматизируема, честно, без имитации полной автоматизации
#       (прямое требование задачи). Обоснование частичной автоматизации:
#       - Буллет «Кросс-каталожные:» (Кириллица) — ЕДИНСТВЕННАЯ строка SKILL.md, содержащая
#         это Кириллическое написание (проверено эмпирически: `grep -n 'Кросс-каталож'
#         SKILL.md` даёт 1 совпадение и до, и после точного текста замены ADR — потому что
#         новый абзац Решения 2 вводит ВТОРОЙ заголовок с ЛАТИНСКИМ написанием «Cross-каталожные
#         ссылки:», не Кириллическим). Это позволяет однозначно, без xargs-цепочки и без риска
#         зацепить соседний ❌-пример (другая строка, другой префикс), выделить именно ту
#         строку, на которую указывает FR-096.
#       - Автоматическая часть: эта строка не должна содержать паттерн markdown-ссылки
#         `[X](Y)` (квадратные + круглые скобки) — именно такой паттерн сегодня утверждает
#         рабочую markdown-форму для кросс-каталожной ссылки, что и есть претензия FR-096.
#         Позитивная альтернатива FR-096 («удалить буллет целиком») тоже обрабатывается корректно
#         — отсутствие строки не считается провалом.
#       - ЧЕСТНО НЕ автоматизируется: что где-то ДАЛЬШЕ по тексту (не в этой конкретной строке)
#         не появится НОВОЕ отдельное утверждение о рабочей markdown-форме для кросс-каталожных
#         ссылок. Regex не может надёжно отличить «утверждение» от «❌-иллюстрации, обёрнутой в
#         обратные кавычки» — сам исправленный текст (Решение 2 ADR) явно предупреждает об этой
#         ловушке для чужих регекс-валидаторов («Ловушка чужих валидаторов»). Пытаться
#         сформулировать более широкий grep означало бы либо повторить ту же ловушку, либо
#         де-факто продублировать разбор Dev-версии текста построчно — имитация автоматизации,
#         которую задание прямо запрещает. Ручной чек-лист — README.md этого suite'а, раздел
#         «Ручная проверка (AC-002в)».

set -u -o pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel)"
source "$SCRIPT_DIR/lib/assert.sh"

FAIL=0
SKILL_MD="$ROOT/plugins/gramax/skills/writer/SKILL.md"

assert_file_exists "$SKILL_MD" "AC-002: SKILL.md должен существовать"

if [ -f "$SKILL_MD" ]; then
  # (a)/(b) идут по FLAT-версии файла (переводы строк схлопнуты в пробел) — та же защита от
  # ложного результата на многословной фразе, разорванной ручным переносом строки, что и в
  # ac-001-doc-root-schema-retracted.sh (см. комментарий там). (в) ниже НАМЕРЕННО не использует
  # FLAT — bullet-isolation там зависит от разбиения по строкам.
  FLAT="$(tr '\n' ' ' < "$SKILL_MD")"

  # (a) негативная
  # shellcheck disable=SC2016  # backtick — литерал ретируемой фразы SKILL.md (`code:`), не command substitution: интерполяция здесь не нужна и не должна происходить
  if printf '%s' "$FLAT" | grep -qF 'Полный рецепт (реальный `code:`)'; then
    echo "  FAIL: AC-002(a) — ссылка на ретируемый рецепт всё ещё присутствует в блоке ## Ссылки (FR-095)" >&2
    FAIL=$((FAIL + 1))
  fi

  # (b) позитивная — regression guard (BR-002)
  if ! printf '%s' "$FLAT" | grep -qF 'inline code'; then
    echo "  FAIL: AC-002(b) — рекомендация 'inline code' для кросс-каталожных ссылок должна остаться (BR-002)" >&2
    FAIL=$((FAIL + 1))
  fi

  # (в) частичная автоматизация — см. заголовочный комментарий.
  BULLET_LINE="$(grep -n 'Кросс-каталож' "$SKILL_MD" | head -1 || true)"
  if [ -z "$BULLET_LINE" ]; then
    echo "  INFO: AC-002(в, частично) — буллет 'Кросс-каталожные' отсутствует (удалён) — допустимая альтернатива FR-096"
  else
    BULLET_TEXT="${BULLET_LINE#*:}"
    if printf '%s' "$BULLET_TEXT" | grep -qE '\[[^]]+\]\([^)]+\)'; then
      echo "  FAIL: AC-002(в, частично) — буллет 'Кросс-каталожные' всё ещё показывает markdown-ссылку [X](Y) как форму кросс-каталожной ссылки (FR-096): $BULLET_LINE" >&2
      FAIL=$((FAIL + 1))
    fi
  fi
  echo "  MANUAL: AC-002(в, полностью) — семантическая проверка снятия противоречия не автоматизируется целиком (честно зафиксировано требованием и ADR-0017). См. README.md → 'Ручная проверка (AC-002в)' перед финальным QA sign-off." >&2
fi

if [ "$FAIL" -gt 0 ]; then fail_msg "ac-002: $FAIL assertion(s) failed"; exit 1; fi
pass_msg "ac-002: блок ## Ссылки согласован (a/b автоматически; в — частично автоматически + обязательная ручная проверка)"
