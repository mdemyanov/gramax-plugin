#!/usr/bin/env bash
# tests/gramax/writer-sync-470/ac-087-link-md-caveat-rule-preserved.sh
# Требование: docs/30-requirements/2026-11-18-writer-sync-470-requirement.md — AC-087 (FR-173).
# Дизайн: кластер A, строка FR-173 — RES-008 вердикт 2: обе формы ссылок (с .md
#   и без) резолвятся на пине; правило «без .md» (FR-080, ADR-0016) остаётся
#   каноном (BR-017), оговорка — информационная: «обе формы резолвятся движком
#   и офлайн-валидатором; форма с .md — валидный, но не канонический для
#   XML/Legacy-каталогов вид; миграция существующих ссылок не обязательна».
# Природа: КРАСНАЯ на момент создания. Красный на a59db10 (2026-11-18):
#   оговорки в SKILL.md нет.
# ЛОВУШКА (найдена авторской предпроверкой, для Dev): текущая строка правила
#   «Внутренние (без `.md`)» НЕ матчится формулой AC-087 'без .md' — обратные
#   кавычки стоят между «без » и «.md», а '.' паттерна съедает ровно один
#   символ. Для зелёного AC-087 формулировка Dev обязана содержать «без .md»
#   БЕЗ бэктиков (например, в самой оговорке). Целевая фраза дизайна —
#   «обе формы резолвятся» (regex-альтернативы AC-087: 'обе формы' /
#   'тоже резолв' / 'резолвятся обе').
# Регрессия (BR-017, зелёная на a59db10): само правило ссылок без `.md`
#   обязано ПЕРЕЖИТЬ вставку оговорки — проверяется backtick-толерантным
#   regex, независимым от ловушки выше.

set -u -o pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel)"
source "$SCRIPT_DIR/lib/assert.sh"

FAIL=0
SKILL_MD="$ROOT/plugins/gramax/skills/writer/SKILL.md"

assert_grep "$SKILL_MD" 'без .md' \
  "AC-087 — SKILL.md должен содержать «без .md» БЕЗ бэктиков между словами (ловушка AC-087: текущее «без \`.md\`» формулу не матчится; красный на a59db10)"
assert_grep_regex_i "$SKILL_MD" 'обе формы|тоже резолв|резолвятся обе' \
  "AC-087 — оговорка о резолве .md-формы обязана содержать дословно одну из фраз «обе формы»/«тоже резолв»/«резолвятся обе» (целевая формулировка дизайна: «обе формы резолвятся»; красный на a59db10 — оговорки нет)"
assert_grep_regex "$SKILL_MD" 'без \`.md' \
  "BR-017/NFR-071 — правило «внутренние ссылки без \`.md\`» сохраняется неизменным (регрессия; зелёная на a59db10 — оговорка не отменяет правило)"

if [ "$FAIL" -gt 0 ]; then fail_msg "ac-087: AC-087 — $FAIL assertion(s) failed"; exit 1; fi
pass_msg "ac-087: AC-087 — правило ссылок сохранено, оговорка «обе формы резолвятся» добавлена"
