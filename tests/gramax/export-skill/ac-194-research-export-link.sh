#!/usr/bin/env bash
# tests/gramax/export-skill/ac-194-research-export-link.sh
# Требование: docs/30-requirements/2026-11-24-wave4-docs-decisions-requirement.md (вне индекса
#   на момент письма) — AC-194 (FR-245, карточка gramax-o0q.18; RES-007).
# Сюита: export-skill — владелец контрактов навыка export (ac-041…ac-050 пиннят SKILL и
#   рецепты); предмет стаба — документарный след навыка export в research RES-007.
# Проверка (контракт):
#   (1) research несёт обратную markdown-ссылку на требование export, и текст ссылки равен
#       title цели (title берётся из H1 требования динамически — форма FR-089: предшественник
#       получает ссылку на реализацию);
#   (2) строки карты покрытия для экспорта и портала документации несут датированную правку
#       «(правка 2026-11-24; 2026-11-18 — не покрыт)» и называют приземливший навык коммитом
#       1409740 — «не покрыт» для экспорта больше не заявляется;
#   (3) вердикт «не проверено» для проверки роутинга триггеров присутствует (второй
#       разрешённый исход карточки — вердикт с причиной).
# Цвет на момент письма (2026-11-24): ЗЕЛЁНЫЙ ГАРД — все три ноги на месте (замер роли;
#   до волны ссылок на требование export было 0 — факт 10 требования).
# Мутации к красному (показаны в at-design 2026-11-24-wave4-docs-at-design.md): удаление
#   ссылки/правки из /tmp-копии RES-007 — соответствующий grep теряет литерал; смена title
#   требования без обновления текста ссылки красит ногу 1 (текст ссылки динамически сверяется
#   с title цели).

set -u -o pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel)"
source "$SCRIPT_DIR/lib/assert.sh"

FAIL=0
REQ="$ROOT/docs/30-requirements/2026-11-18-export-skill-requirement.md"
RES="$ROOT/docs/10-domain/research/2026-11-18-enterprise-server-skill-gap.md"

assert_file_exists "$REQ" "AC-194: требование export на месте (цель обратной ссылки)"
assert_file_exists "$RES" "AC-194: research RES-007 на месте"

# --- Нога 1: обратная ссылка с текстом = title цели (динамическая сверка) ---
TITLE="$(awk '/^# /{sub(/^# /, ""); print; exit}' "$REQ")"
LINK_LINE="$(grep -F '2026-11-18-export-skill-requirement.md' "$RES" | head -1 || true)"
if [ -n "$TITLE" ] && printf '%s\n' "$LINK_LINE" | grep -qF "[$TITLE]("; then
  :
else
  echo "  FAIL: AC-194 — RES-007 не несёт обратной ссылки на требование export с текстом" >&2
  echo "  ссылки, равным title цели («${TITLE:-<title не прочитан>}»); строка с целью:" >&2
  echo "  «${LINK_LINE:-<строки с целью нет>}» (форма FR-089: предшественник получает ссылку" >&2
  echo "  на реализацию)" >&2
  FAIL=$((FAIL + 1))
fi

# --- Нога 2: датированные правки строк экспорта и портала + коммит приземления ---
CORR="$(grep -cF '(правка 2026-11-24; 2026-11-18 — не покрыт)' "$RES" || true)"
if [ "${CORR:-0}" -ge 3 ]; then
  :
else
  echo "  FAIL: AC-194 — датированную правку «(правка 2026-11-24; 2026-11-18 — не покрыт)»" >&2
  echo "  несут ${CORR:-0} строк(и), нужно ≥ 3 (экспорт, портал, CI/CD — строки карты покрытия)" >&2
  FAIL=$((FAIL + 1))
fi
# shellcheck disable=SC2016  # бэктики — дословный литерал markdown из RES-007
COMMIT="$(grep -cF 'коммит `1409740`' "$RES" || true)"
if [ "${COMMIT:-0}" -ge 3 ]; then
  :
else
  echo "  FAIL: AC-194 — приземлившийся навык назван коммитом \`1409740\` в ${COMMIT:-0} строк(ах)," >&2
  echo "  нужно ≥ 3 (исправленные строки указывают приземлённый навык с датой, не «не покрыт»)" >&2
  FAIL=$((FAIL + 1))
fi

# --- Нога 3: вердикт «не проверено» для роутинга триггеров ---
assert_grep "$RES" '| Роутинг триггеров | **не проверено**' \
  "AC-194: проверка семантики роутинга триггеров завершена вердиктом «не проверено» с причиной (разрешённый исход карточки)"

if [ "$FAIL" -gt 0 ]; then fail_msg "ac-194: $FAIL assertion(s) failed"; exit 1; fi
pass_msg "ac-194: RES-007 несёт обратную ссылку (текст = title цели), три датированные правки с коммитом 1409740 и вердикт «не проверено» на роутинг триггеров"
