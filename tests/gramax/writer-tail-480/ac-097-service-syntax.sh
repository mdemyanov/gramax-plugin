#!/usr/bin/env bash
# tests/gramax/writer-tail-480/ac-097-service-syntax.sh
# Требование: docs/30-requirements/2026-11-18-writer-tail-480-requirement.md — AC-097 (FR-183).
# Дизайн: docs/40-architecture/2026-11-18-writer-tail-480-design.md — FR-183, раздел
#   «Служебная синтаксика» (NEW между «Блок кода» и «Якоря заголовков» blocks.md);
#   шесть форм: тире `--`, перенос `\`, экранирование `\$` и `\[note]`,
#   HTML-комментарий `<!-- … -->`, экранирование точки `5\.1` (переезд из «Спецсимволов»).
# Природа: КРАСНАЯ на момент создания. Красный на 894f3fd (2026-11-18): все маркеры
#   формул AC («тире», «\$», «<!--») и FR-183-буквы («\[note]») в blocks.md — ноль
#   совпадений; заголовка «Служебная синтаксика» нет; «Спецсимволы» ещё не свёрнуты.
# Уровень: integration (grep по references/blocks.md; контракт с QA-author дизайна).
# Design-derived ассерты (сверх формулы AC): заголовок «Служебная синтаксика» есть;
#   заголовок «Спецсимволы» отсутствует (свертка раздела — одно место истины);
#   форма `5\.1` переживает переезд дословно (регрессия, зелёная с рождения).
# Helper'ы инлайн (копия lib/assert.sh волны writer-sync-470): suite без lib/ и
#   без run.sh по брифу потока — семь скриптов + README, ничего больше.

set -u -o pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel)"

FAIL=0

fail() {
  printf '  FAIL: %s\n' "$1" >&2
  FAIL=$((FAIL + 1))
}

pass_msg() { printf '%b[PASS]%b %s\n' '\033[0;32m' '\033[0m' "$1"; }
fail_msg() { printf '%b[FAIL]%b %s\n' '\033[0;31m' '\033[0m' "$1"; }

assert_grep() {
  local file="$1" pattern="$2" msg="$3"
  if ! grep -qF "$pattern" "$file" 2>/dev/null; then
    fail "$msg — не найдено: '$pattern' в $file"
  fi
}

assert_no_grep_regex() {
  local file="$1" pattern="$2" msg="$3"
  if grep -qE "$pattern" "$file" 2>/dev/null; then
    fail "$msg — неожиданное совпадение regex: '$pattern' в $file"
  fi
}

BLOCKS_MD="$ROOT/plugins/gramax/skills/writer/references/blocks.md"

# Формула AC-097 требования (три фиксированных маркера служебной синтаксики).
assert_grep "$BLOCKS_MD" 'тире' \
  "AC-097 — blocks.md должен документировать тире внутри строки (FR-183: форма '--'; красный на 894f3fd — маркера нет; формулировке нужен хотя бы один строчный 'тире', как в целевой таблице дизайна: «рендерятся тире»)"
assert_grep "$BLOCKS_MD" '\$' \
  "AC-097 — blocks.md должен документировать экранирование знака доллара (FR-183: форма '\\\$' — показать знак, не открыв формулу; красный на 894f3fd)"
assert_grep "$BLOCKS_MD" '<!--' \
  "AC-097 — blocks.md должен документировать HTML-комментарий (FR-183: '<!-- … -->' виден только в исходнике; красный на 894f3fd)"

# Буква FR-183 сверх формулы AC: экранирование скобочного литерала.
assert_grep "$BLOCKS_MD" '\[note]' \
  "AC-097 — blocks.md должен документировать экранирование скобочного литерала (FR-183: '\[note]' — показать скобки, не вызвав эффект синтаксиса; красный на 894f3fd)"

# Design-derived: сводный раздел по решению о размещении (открытый вопрос 2 требования).
assert_grep "$BLOCKS_MD" 'Служебная синтаксика' \
  "AC-097 — в blocks.md должен появиться раздел «Служебная синтаксика» (дизайн: NEW между «Блок кода» и «Якоря заголовков»; красный на 894f3fd — раздела нет)"

# Design-derived: «Спецсимволы» сворачиваются — заголовок обязан исчезнуть (одно место истины).
assert_no_grep_regex "$BLOCKS_MD" '^#+ Спецсимволы' \
  "AC-097 — заголовок «Спецсимволы» обязан исчезнуть из blocks.md (дизайн: содержание свернуто в «Служебную синтаксику», второй носитель класса убирается; красный на 894f3fd — заголовок ещё на месте)"

# Регрессия свертки: форма экранирования точки переезжает дословно (зелёная с рождения).
assert_grep "$BLOCKS_MD" '5\.1' \
  "AC-097 — форма '5\.1' обязана пережить свертку «Спецсимволов» (дизайн FR-183, шестая форма таблицы: переезд дословно; зелёная регрессия с рождения на 894f3fd)"

if [ "$FAIL" -gt 0 ]; then fail_msg "ac-097: AC-097 — $FAIL assertion(s) failed"; exit 1; fi
pass_msg "ac-097: AC-097 — служебная синтаксика задокументирована в blocks.md (раздел «Служебная синтаксика», «Спецсимволы» свернуты)"
