#!/usr/bin/env bash
# tests/gramax/writer-tail-480/ac-098-negative-list.sh
# Требование: docs/30-requirements/2026-11-18-writer-tail-480-requirement.md — AC-098 (FR-184).
# Дизайн: docs/40-architecture/2026-11-18-writer-tail-480-design.md — FR-184, раздел
#   «Чего нет в синтаксисе» (NEW сразу за «Служебной синтаксикой» blocks.md): ровно
#   четыре формы (setext `===`, сноски, `==выделение==`, авто-ссылки) + замыкающий
#   абзац классов отсутствия (BR-020: развёртки таблиц — «ждёт вердикта», не «нет»).
# Природа: КРАСНАЯ на момент создания. Красный на 894f3fd (2026-11-18): маркеры
#   формул AC («чего нет», «===», «снос») в blocks.md — ноль совпадений; проза
#   «развёртки/ждёт/очередь» тоже отсутствует.
# Уровень: integration (grep по references/blocks.md; контракт с QA-author дизайна).
# Ловушка регистра (README, ловушка 1): формула AC чувствительна к регистру, а
#   заголовок дизайна — «Чего нет в синтаксисе» с заглавной (начало предложения,
#   регистр формулу НЕ удовлетворяет). Stub держит букву формулы: Dev обязан дать
#   хотя бы одно СТРОЧНОЕ «чего нет» mid-sentence (естественное место — вводная
#   строка раздела), иначе буквальный AC-снипет требования остаётся красным.
# Edge case дизайна (прецедент AC-082 cover): grep '===' — позитивный grep
#   НЕГАТИВНОГО употребления; тест не отличает «документируем отсутствие» от
#   «используем» — смысловой контроль на ревьюере, пример формы только в
#   ограждённом код-блоке. Проза об отсутствующих формах — без литеральных
#   ключей развёрток (AC-102 — байтовый негатив по всему дереву writer).
# Helper'ы инлайн (копия lib/assert.sh волны writer-sync-470): suite без lib/ и
#   без run.sh по брифу потока — семь скриптов + README, ничего больше.

set -u -o pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(git -C "$SCRIPT_DIR" rev-parse --show-toplevel)"

FAIL=0

fail() {
  printf '  FAIL: %s\n' "$1" >&2
  FAIL=$((FAIL + 1))
}

pass_msg() { printf '%b[PASS]%b %s\n' '\033[0;32m' '\033[0m' "$1"; }
fail_msg() { printf '%b[FAIL]%b %s\n' '\033[0;31m' '\033[0m' "$1"; }

assert_grep() {
  local file="$1" pattern="$2" msg="$3"
  if ! grep -qF "$pattern" "$file" 2>/dev/null; then
    fail "$msg — не найдено: '$pattern' в $file"
  fi
}

assert_grep_regex_i() {
  local file="$1" pattern="$2" msg="$3"
  if ! grep -qiE "$pattern" "$file" 2>/dev/null; then
    fail "$msg — не найдено (regex без учёта регистра): '$pattern' в $file"
  fi
}

BLOCKS_MD="$ROOT/plugins/gramax/skills/writer/references/blocks.md"

# Формула AC-098 требования (буква формулы, с учётом ловушки регистра — см. шапку).
assert_grep "$BLOCKS_MD" 'чего нет' \
  "AC-098 — в blocks.md должен появиться негативный перечень «Чего нет в синтаксисе» (FR-184; красный на 894f3fd — маркера нет; формула AC чувствительна к регистру: заголовок «Чего нет…» с заглавной её НЕ удовлетворяет — добавь строчное «чего нет» mid-sentence, например во вводной строке раздела)"
assert_grep "$BLOCKS_MD" '===' \
  "AC-098 — blocks.md должен называть setext-заголовки ('===' в подписи под строкой) отсутствующими (FR-184; красный на 894f3fd; позитивный grep негативного употребления — контроль смысла на ревьюере, прецедент AC-082)"
assert_grep "$BLOCKS_MD" 'снос' \
  "AC-098 — blocks.md должен называть сноски отсутствующими (FR-184; красный на 894f3fd — стемма «снос» не встречается)"

# Design-derived: замыкающий абзац классов отсутствия (BR-020) — маркер «ждёт»/«очередь»
# в одной строке с «развёртками таблиц»; без литеральных ключей развёрток (AC-102).
# [её] — толерантность к ё/е; одна строка markdown — контракт дешёвого грепа (README, ловушка 5).
assert_grep_regex_i "$BLOCKS_MD" '(ждёт|очеред).*разв[её]ртк|разв[её]ртк.*(ждёт|очеред)' \
  "AC-098 — замыкающий абзац обязан разводить классы отсутствия: развёртки таблиц «ждут engine-вердикта» в очереди BR-020, а не объявлены отсутствующими (дизайн FR-184; красный на 894f3fd — прозы о развёртках нет; формулировка — без литеральных ключей: 'aggregation' и под. запрещены AC-102)"

if [ "$FAIL" -gt 0 ]; then fail_msg "ac-098: AC-098 — $FAIL assertion(s) failed"; exit 1; fi
pass_msg "ac-098: AC-098 — негативный перечень «Чего нет в синтаксисе» задокументирован (4 формы + граница классов отсутствия BR-020)"
