#!/usr/bin/env bash
# role-postflight.sh [файл-теста…] — самопроверка роли ОДНИМ вызовом, сводкой, а не тремя выводами.
#
# ЗАЧЕМ (план волны NA-EPIC-52 Т4). Последний шаг роли — три прогона подряд (`check.sh --fast`,
# `validate-content`, точечные тесты), и каждый возвращал в контекст полный вывод; замер §1.2
# спутника ADR-102: 53 вызова `pytest`/`check.sh` за 2,3 волны по правилу исполняемой позиции.
# Здесь шаги идут ЗА ОДИН вызов, а вывод каждого уходит в файл через `run-quiet.sh`.
#
# ПОЧЕМУ ШАГИ НЕ ОБРЫВАЮТСЯ НА ПЕРВОМ КРАСНОМ. Роль, узнавшая только о первом падении, идёт
# гонять остальное руками — то есть возвращает в контекст ровно то, что вынесено. Поэтому
# исполняются ВСЕ шаги, а сводка называет исход каждого поимённо.
#
# ПРОГОН ТЕСТОВ НАЗЫВАЕТ ФАЙЛЫ. Аргументов нет — шаг тестов не исполняется вовсе и это
# сказано: сбор по каталогу внутри роли запрещён ресурсной дисциплиной (ADR-102 Д3, §8.6
# спутника), и обёртка не имеет права его обойти.
#
# ЧЕТВЁРТЫЙ ШАГ — ОКРЕСТНОСТЬ ПРЕДМЕТА (ADR-107 Д4). Именованные тесты роли и окрестность
# предмета — РАЗНЫЕ множества, и второе не заменяет первого: роль называет то, что писала, а
# окрестность собирается объявлениями `Governs:` тестов предмета. Код шага входит в свёртку
# `rc` наравне с тремя существующими. Предмет задачи прибор выводит из файлов сам; когда среди
# них нет ни требования, ни ADR (а обязанность сработала), роль называет предмет переменной
# NAUTA_TASK_SUBJECT='capability=<slug> adr=ADR-NNN' — шаг разворачивает её в аргументы прибора.
# У самого прибора переменной предмета НЕТ: она меняла бы исход прямого замера молча.
#
# ПЯТЫЙ БЛОК — ДИФ-СКОУПИНГ (замер сессии 28.10.2026). Красное в выводах гейтов делится на
# «моё» и «предсуществующее»; без этой сводки роль доказывает разделение сама — грепает
# сохранённые выводы руками (в замере: два хода только на то, чтобы показать, что чужие
# «Errors» не про её файлы). Блок берёт изменённые файлы из `git status` и ищет их в выводах
# ЭТОГО прогона (файлы run-quiet моложе метки старта). Блок информационный и в свёртку rc НЕ
# входит: он сортирует уже названные шагами нарушения, исход шага не меняет.
#
# Usage: bash scripts/role-postflight.sh [--no-task] [tests/test_x.py tests/test_y.py::test_z …]
set -u

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO" || exit 2
QUIET="$REPO/scripts/run-quiet.sh"
[ -f "$QUIET" ] || { echo "ОШИБКА: нет $QUIET — сводке не через что идти" >&2; exit 2; }
# 17 строк на шаг: четыре шага плюс заголовок и вердикт укладываются в 73 строки — предел
# сводки постфлайта в контексте роли (план Т2 «≤ 20 строк» на носитель, четыре носителя плюс
# рамка).
export NAUTA_QUIET_MAX_LINES="${NAUTA_QUIET_MAX_LINES:-17}"

# Метка старта прогона: пятый блок берёт только логи run-quiet, созданные после неё.
POSTFLIGHT_MARK="$(mktemp)"
trap 'rm -f "$POSTFLIGHT_MARK"' EXIT

# РАЗВЕДЕНИЕ ФЛАГОВ ЗАДАЧИ И АРГУМЕНТОВ ТЕСТОВ — до какого-либо вызова (SA-154 §3). Обёртка
# разбирает СВОИ аргументы списком известных флагов: `--no-task` (семантика как у префлайта
# DEV-481) поглощается с одной строкой в сводке — это флаг задачи, НЕ «пропустить тесты»:
# бриф без задачи вправе называть файлы. Неизвестный `--*`-токен — именованный отказ с токеном
# и путём носителя одной записью (gate-failure-semantics), не тихая пересылка в pytest, где он
# падал бы usage-ошибкой rc=4. Файлы тестов передаются дословно, порядок сохранён.
NO_TASK_ACCEPTED=""
TEST_ARGS=()
for _arg in "$@"; do
  case "$_arg" in
    --no-task) NO_TASK_ACCEPTED="$_arg" ;;
    --*)
      echo "ОТКАЗ: scripts/role-postflight.sh — неизвестный флаг '$_arg': обёртка знает только --no-task (флаг задачи); прочие --*-токены в argv pytest не пересылаются (SA-154 §3)" >&2
      exit 2
      ;;
    *) TEST_ARGS+=("$_arg") ;;
  esac
done

printf '===== ПОСТФЛАЙТ РОЛИ (%s) =====\n' "$REPO"

printf '[1/4] check.sh --fast\n'
bash "$QUIET" bash "$REPO/scripts/check.sh" --fast
rc_check=$?

printf '[2/4] validate-content.py\n'
bash "$QUIET" uv run "$REPO/scripts/validate-content.py"
rc_content=$?

if [ -n "$NO_TASK_ACCEPTED" ]; then
  printf '%s принят: флаг задачи, не тестов — в argv pytest не попадёт (SA-154 §3)\n' "$NO_TASK_ACCEPTED"
fi
if [ "${#TEST_ARGS[@]}" -eq 0 ]; then
  printf '[3/4] тесты НЕ названы — шаг не исполнен (сбор по каталогу внутри роли запрещён)\n'
  rc_tests=0
else
  printf '[3/4] pytest %s\n' "${TEST_ARGS[*]}"
  bash "$QUIET" uv run --with pytest pytest "${TEST_ARGS[@]}" -q
  rc_tests=$?
fi

printf '[4/4] окрестность предмета\n'
HOOD="$REPO/scripts/subject-neighbourhood.py"
if [ ! -f "$HOOD" ]; then
  # Громкий ноль, а не тихий проход: у дерева, получившего постфлайт без прибора, причина
  # названа (ADR-107 Д7, ADR-007 Д1) — прибор этой волной потребителю не доставляется.
  printf 'окрестность: прибора scripts/subject-neighbourhood.py в этом дереве нет — шаг не исполнен\n'
  rc_neighbourhood=0
else
  # Среду в АРГУМЕНТ разворачивает зовущий: у прибора переменной предмета нет, иначе она меняла
  # бы исход прямого замера молча. Пусто — предмет выводится из файлов предмета самим прибором.
  hood_subject=""
  for s in ${NAUTA_TASK_SUBJECT:-}; do hood_subject="$hood_subject --subject $s"; done
  # shellcheck disable=SC2086 — разбиение на слова здесь предмет, а не оплошность
  bash "$QUIET" uv run "$HOOD" --run $hood_subject
  rc_neighbourhood=$?
fi

# Пятый блок — диф-скоупинг (описание в шапке). Меняет умолчание NAUTA_QUIET_DIR тем же
# правилом, что и run-quiet.sh: явная переменная → общий git-каталог, иначе системный TMPDIR.
printf '[диф] изменённые файлы против выводов шагов\n'
if ! _changed="$(git status --porcelain 2>/dev/null | sed -e 's/^...//' -e 's/.* -> //' | grep -v '^$')"; then
  _changed=""
fi
if [ -z "$_changed" ]; then
  printf 'изменённых файлов нет — дерево чистое\n'
else
  _quiet_dir="${NAUTA_QUIET_DIR:-}"
  if [ -z "$_quiet_dir" ]; then
    _quiet_dir="$(git rev-parse --git-common-dir 2>/dev/null || true)"
    _quiet_dir="${_quiet_dir%/}/nauta-quiet"
  fi
  # shellcheck disable=SC2086 — пути git и run-quiet без пробелов; разбиение здесь предмет
  _step_logs="$(find "$_quiet_dir" -maxdepth 1 -name 'run-quiet-*' -newer "$POSTFLIGHT_MARK" 2>/dev/null | sort)"
  _mentioned=""
  for _f in $_changed; do
    _cnt="$(grep -a -l -F "$_f" $_step_logs 2>/dev/null | wc -l | tr -d ' ')"
    if [ "$_cnt" -gt 0 ]; then _mentioned="${_mentioned}${_f} — упомянут в ${_cnt} выводе/ах\n"; fi
  done
  if [ -z "$_step_logs" ]; then
    printf 'выводов этого прогона не найдено — сверить не с чем\n'
  elif [ -z "$_mentioned" ]; then
    printf 'изменённые файлы в выводах шагов НЕ упомянуты — красное (если есть) предсуществующее\n'
  else
    printf 'упомянуты — проверять в первую очередь:\n'
    printf '%b' "$_mentioned" | head -5
  fi
fi

# Носитель отказов записи стадии (ADR-133 Ш-3/З-3). Трасса отказа в stderr процесса хука
# (hooks/stage-writer.py: нет различимого субъекта, отсутствующий корень стора) потребителя
# не имеет — постфлайт здесь её поимённый читатель: содержимое носителя печатается, стадия
# эпика называется незаписанной. Шаг информационный и в свёртку rc не входит: незаписанная
# стадия — наблюдаемое состояние платформенного шва, а не провал работы самой роли; но молчать
# о нём постфлайт не имеет права — носитель без читателя та же потеря, что трасса в stderr.
CARRIER_NAME=".nauta-stage-write-refusals.jsonl"
if [ -f "$REPO/$CARRIER_NAME" ] && [ -s "$REPO/$CARRIER_NAME" ]; then
  printf 'носитель отказов записи стадии %s — стадия эпика НЕ записана, отказ(ы):\n' \
    "$CARRIER_NAME"
  tail -n 5 "$REPO/$CARRIER_NAME" | cut -c1-200
  printf 'носитель отказов: всего %s строк(и)\n' \
    "$(wc -l < "$REPO/$CARRIER_NAME" | tr -d ' ')"
else
  printf 'носитель отказов записи стадии (%s) пуст — незаписанных отказов нет\n' \
    "$CARRIER_NAME"
fi

rc=0
for r in "$rc_check" "$rc_content" "$rc_tests" "$rc_neighbourhood"; do [ "$r" -ne 0 ] && rc=1; done
printf 'постфлайт: rc=%s — check.sh=%s validate-content=%s pytest=%s окрестность=%s\n' \
  "$rc" "$rc_check" "$rc_content" "$rc_tests" "$rc_neighbourhood"
exit "$rc"
