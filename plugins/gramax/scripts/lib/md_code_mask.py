"""Маскирование кода (fenced + inline) для валидаторов Gramax.

Единственный источник правды для анти-ложносрабатывающего примитива маскирования
кода: и `validate_structure.py`, и `validate_render.py` импортируют его из `lib/`
(ADR-0019, Решение 5). Копия в два места дрейфовала бы (дух BR-002).

Статья, документирующая Gramax-синтаксис, может показывать `<note>`, `{{ИМЯ}}`
или `[пример](ссылка.md)` как иллюстрацию, а не как реальную разметку — без маски
баланс-/киллер-/ссылочные проверки давали бы ложные срабатывания. Маскирование
заменяет код пробелами той же длины, сохраняя смещения строк (номера строк
остаются валидными для отчётов).

Тот же приём для блоков сырого HTML `<html>…</html>` (FR-216, ADR-0026 через
`_mask_html_blocks`): движок пропускает их содержимое как есть — внутри легальны
любые HTML-теги, и построчные проверки (W034, W035) и баланс не должны судить их
как разметку страницы. Механика — порт `html_mask()` апстрим-линтера
(провенанс — `LICENSE.upstream.md`, ADR-0019).
"""

import re

_FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")
_INLINE_CODE_RE = re.compile(r"(`+)([^\n]+?)\1")
# Html-теги внешнего уровня: открывающий (форма с атрибутами допускается — парсер тегов
# движка общий для pairedTags; самозакрытая `<html/>` не считается ни открывающим, ни
# закрывающим — та же семантика, что у открывающего регэкспа check_tags) и закрывающий.
# Маска убирает СОДЕРЖИМОЕ между такими тегами, но сами теги никогда не убирает и не
# схлопывает — счёт баланса html точен на любой глубине вложенности (регрессия замера
# 2026-11-23: сопоставление «до ближайшего </html>» съедало внутренний <html lang="ru">
# и давало ложное «unpaired <html>: 1 open, 2 close»).
_HTML_TAG_RE = re.compile(r"</?html(?:\s[^>]*)?>")


def _mask_code(text: str) -> str:
    """Заменяет код (fenced-блоки и inline) пробелами той же длины, сохраняя смещения строк.

    Статья, документирующая Gramax-синтаксис, может показывать `[пример](ссылка.md)` или
    `{{ИМЯ}}` как иллюстрацию, а не как реальную ссылку/протёкший плейсхолдер. Без маски
    orphan-/broken-link-/placeholder-проверки давали бы ложные срабатывания на таких примерах.
    """
    out: list[str] = []
    fence_char: str | None = None
    fence_len = 0
    for line in text.split("\n"):
        m = _FENCE_RE.match(line)
        if fence_char is None:
            if m:
                fence_char, fence_len = m.group(1)[0], len(m.group(1))
                out.append(" " * len(line))
            else:
                out.append(line)
            continue
        if m and m.group(1)[0] == fence_char and len(m.group(1)) >= fence_len and not m.group(2).strip():
            fence_char, fence_len = None, 0
        out.append(" " * len(line))
    return _INLINE_CODE_RE.sub(lambda m: " " * len(m.group(0)), "\n".join(out))


def _mask_html_blocks(text: str) -> str:
    """Заменяет содержимое html-блоков пробелами той же длины, сохраняя смещения строк
    (FR-216, ADR-0026; механика апстрим-`html_mask()`).

    Вложенность (регрессия замера 2026-11-23): маска убирает только содержимое МЕЖДУ
    html-тегами — сами теги `<html …>`/`</html>` на любой глубине остаются на месте, и
    счёт баланса `html` в `check_tags` точен для любой конструкции (обёртка с вложенным
    блоком — 2 open, 2 close; непарная обёртка — находка; соседние блоки — дефект МЕЖДУ
    ними виден). Глубина считается по пройденным тегам: содержимое маскируется, пока
    открыт хотя бы html-блок; самозакрытая `<html/>` и закрывающий без открывающего —
    не границы содержимого; незакрытый `<html>` без `</html>` regions не образует — хвост
    после него не маскируется, баланс остаётся находкой. Прочие парные теги внутри
    (note, td, …) маскируются вместе с содержимым — их баланс не считает страницу.

    Применяется ПОСЛЕ `_mask_code` (дизайн волны-3 §6): `<html>` внутри fenced- или
    inline-кода уже замаскирован и маску не переключает.
    """
    out: list[str] = []
    pos = 0
    depth = 0
    for m in _HTML_TAG_RE.finditer(text):
        segment = text[pos:m.start()]
        if depth > 0:
            out.append(re.sub(r"[^\n]", " ", segment))
        else:
            out.append(segment)  # вне html-блоков текст остаётся как есть
        out.append(m.group(0))  # тег html остаётся — баланс считает его
        pos = m.end()
        if m.group(0).startswith("</"):
            depth = max(depth - 1, 0)
        else:
            depth += 1
    out.append(text[pos:])
    return "".join(out)
